"""Offline tests for evidence.py passage retrieval and the v5-aware claim extraction."""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import claims  # noqa: E402
import evidence  # noqa: E402

DOC = {
    "paragraphs": [
        {"p": "abstract", "s": "abstract", "text": "We study planning for web agents and report pass rates."},
        {"p": "S1.p1", "s": "S1", "text": "Web agents are popular (Smith et al., 2024)."},
        {"p": "S4.p2", "s": "S4", "text": "Adding the planner raises the pass rate on WebArena from 14% to 26%."},
        {"p": "S4.p3", "s": "S4", "text": "Training cost grows linearly with the number of demonstrations."},
        {"p": "S5.p1", "s": "S5", "text": "The planner fails on tasks that need more than twenty steps."},
    ]
}

V5_REPORT = """# Review

## Themes

A planner raises the WebArena pass rate from 14% to 26% (Smith et al., 2025) [E3, E4].

## References

Smith, A. (2025). Planning web agents. arXiv. https://arxiv.org/abs/2501.00001

<!-- evidence-appendix: generated by the citation gate from checked quotes; edits here are overwritten -->

## Evidence

| Id | Paper | Location | Quote |
|---|---|---|---|
| E3 | arXiv:2501.00001 | [4 Experiments](https://arxiv.org/html/2501.00001#S4.p2) | “raises the pass rate on WebArena from 14% to 26%” |

Code checked that every quote appears word for word (Smith et al., 2025) in the paper.

<!-- /evidence-appendix -->
"""


class PassageTest(unittest.TestCase):
    def test_best_matching_body_paragraphs_first_abstract_excluded(self):
        found = evidence.passages(DOC, "Smith et al. (2025) report that a planner raises the WebArena pass rate [E3].")
        self.assertEqual(found[0]["p"], "S4.p2")
        self.assertNotIn("abstract", [p["p"] for p in found])
        self.assertLessEqual(len(found), evidence.K)

    def test_no_overlap_means_no_passages(self):
        self.assertEqual(evidence.passages(DOC, "Quantum chromodynamics lattice."), [])
        self.assertIn("judge from the abstract", evidence.passage_block([]))

    def test_markers_are_removed_from_claims(self):
        self.assertEqual(evidence.strip_markers("It works (Smith, 2025) [E3, E12]."), "It works (Smith, 2025).")


class V5ExtractionTest(unittest.TestCase):
    def test_appendix_is_not_a_claim_and_markers_are_kept_aside(self):
        found, _ = claims.extract_claims(V5_REPORT)
        self.assertEqual(len(found), 1)
        self.assertEqual(found[0]["text"], "A planner raises the WebArena pass rate from 14% to 26% (Smith et al., 2025).")
        self.assertEqual(found[0]["evidence"], ["E3", "E4"])
        self.assertEqual(found[0]["ids"], ["2501.00001"])

    def test_v3_prompt_carries_passages_not_the_reports_quotes(self):
        claim = {"text": "A planner raises the WebArena pass rate (Smith et al., 2025).", "ids": ["2501.00001"], "kind": "synthesis"}
        prompt = claims.judge_prompt("v3", {"title": "Planning web agents", "abstract": "We study planning."}, claim, "2501.00001", {}, DOC)
        self.assertIn("[S4.p2] Adding the planner raises the pass rate", prompt)
        self.assertNotIn("[E3]", prompt)


if __name__ == "__main__":
    unittest.main()


ANNOTATED_BIB = """# Review

## Annotated Bibliography

**Wei, J., & Sun, Z. (2025).** BrowseComp: A benchmark for browsing agents. *arXiv preprint arXiv:2504.12516*. https://arxiv.org/abs/2504.12516

This paper introduces BrowseComp, a benchmark of 1,266 hard browsing questions.

**Zhou, P., & Leon, B. (2025).** BrowseComp-ZH: Benchmarking web browsing in Chinese. *arXiv preprint arXiv:2504.19314*. https://arxiv.org/abs/2504.19314

BrowseComp-ZH evaluates agents on the Chinese web with 289 multi-hop questions.
"""


class AnnotatedBibliographyTest(unittest.TestCase):
    def test_each_reference_line_owns_the_paragraph_below_it(self):
        found, _ = claims.extract_claims(ANNOTATED_BIB)
        self.assertEqual([(c["ids"], c["kind"]) for c in found], [(["2504.12516"], "annotation"), (["2504.19314"], "annotation")])
        found, _ = claims.extract_claims(ANNOTATED_BIB.replace("## Annotated", "### Annotated"))
        self.assertEqual([c["ids"] for c in found], [["2504.12516"], ["2504.19314"]])


class NumberedHeadingTest(unittest.TestCase):
    def test_multi_level_numbered_heading_with_the_title_owns_its_block(self):
        report = "# R\n\n## Review\n\n#### 3.1.1 Planning web agents\n\n**Results:** The planner doubles the pass rate on long tasks [E1].\n\n## References\n\nSmith, A. (2025). Planning web agents. arXiv. https://arxiv.org/abs/2501.00001\n"
        found, _ = claims.extract_claims(report)
        self.assertEqual([(c["ids"], c["kind"]) for c in found], [(["2501.00001"], "annotation")])
